export type SymbolEntry = { value: string; name: string; category: string };
export const symbolEntries: SymbolEntry[] = [
  ...measurementSymbols.map(([value, name, category]) => ({
    value,
    name,
    category,
  })),
  ...emojiGroups.flatMap((group) =>
    group.entries.split(";").map((entry) => {
      const [value, name] = entry.split("|");
      return { value, name, category: group.name };
    }),
  ),
];
